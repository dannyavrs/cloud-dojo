/** Regenerates the gaps table in README.md and docs/EMULATOR-GAPS.md from shared/gaps.ts. `bun scripts/gen-gaps.ts` */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { gapsMarkdown } from '../shared/gaps'

const root = path.resolve(import.meta.dirname, '..')
const BEGIN = '<!-- gaps:begin (generated by scripts/gen-gaps.ts from shared/gaps.ts) -->'
const END = '<!-- gaps:end -->'
export const block = () => `${BEGIN}\n${gapsMarkdown()}\n${END}`

for (const f of ['README.md', 'docs/EMULATOR-GAPS.md']) {
  const file = path.join(root, f)
  const text = readFileSync(file, 'utf8')
  const re = new RegExp(`${BEGIN.replace(/[()]/g, '\\$&')}[\\s\\S]*?${END}`)
  if (!re.test(text)) { console.error(`${f}: gaps markers not found`); process.exit(1) }
  writeFileSync(file, text.replace(re, () => block()))
  console.log(`updated ${f}`)
}
